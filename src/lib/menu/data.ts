type Seed = Omit<
  MenuItem,
  "currency" | "source" | "lastVerifiedAt" | "verification"
> & {
  source?: PriceSource;
  verification?: Verification;
};

const boardItem = (seed: Seed): MenuItem => ({
  ...seed,
  currency: "INR",
  verification: seed.verification ?? confirmed,
  source: seed.source ?? BOARD,
  lastVerifiedAt: CAPTURED_AT,
});

