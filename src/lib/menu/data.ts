/** Size / portion groups price the whole line, so they replace the base price. */
const portionGroup = (id: string, name: string, options: [string, number, boolean?][]): ModifierGroup => ({
  id,
  name,
  required: true,
  minSelections: 1,
  maxSelections: 1,
  priceMode: "absolute",
  options: options.map(([label, price, isDefault]) => ({
    id: `${id}-${label.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    name: label,
    pricePaise: price,
    isDefault,
  })),
});

